        <br><br>
        The interface features a central vinyl record that acts as the timer, allowing users to choose between different productivity rhythms: Classic (25/5), Deep (50/10), and Flow (90/20). To enhance focus, I integrated an audio system where users can toggle between Ambient sounds and Radio streams. Additionally, I implemented a customizable appearance system with multiple color palettes and a "Focus Notes" feature, enabling users to type and pin their current task directly on the screen to stay on track.
