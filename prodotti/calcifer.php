    <div class="bottom">
        <span class="text">Calcifer is an app I created purely for fun and as a personal practice project. I developed it during the NBA Playoffs to organize a custom tournament with friends, inspired by real Playoff but built entirely from scratch.
        Each user drafts a roster of NBA players and earns points based on their real-life performances (points, rebounds, assists) across multiple rounds. 
        Additionally, users can earn 50+ points in the leaderboard by correctly predicting the winning team of the playoffs. 
        The app is divided into phases that mirror the real NBA brackets: First Round, Quarters, Semi-Finals, and Finals. 
        For each phase, users must set a lineup of 7 players, including 1 captain who earns double points.
        <br><br>For FNBA, I worked across several areas:<br>
        - Database design to manage teams, players, stats and scores.<br>
        - API integration and data scraping from official sources (ESPN).<br>
        - Dynamic scoring system based on daily player stats.<br>
        - Tournament structure with elimination rounds and multiple games (Game 1, Game 2, etc.).<br>
        - Responsive web interface with drag & drop features for roster management (PWA based).<br>
        - Push notifications using OneSignal for real-time updates.<br><br>
        Beyond technical development, I also took care of branding, aiming to make the app accessible, clear, and fun for casual competition among friends.
        FNBA was not only a way to practice working with databases, APIs, and data scraping, but also a way to blend my passion for basketball with building engaging digital experiences.</span>
